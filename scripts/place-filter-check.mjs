import assert from "node:assert/strict";

export async function checkPlaceFilter(page) {
  const button = name => page.getByRole("button",{name,exact:true});
  const box = id => page.locator('.place-results input').and(page.locator('[value="'+id+'"]'));
  const count = async () => Number((await page.locator(".chip").filter({hasText:"Fires"}).locator(".chip-count").innerText()).replaceAll(",",""));
  const initial = await count();
  await button("Filter places").click();
  const search = page.getByRole("searchbox");
  await box("country:SAU").waitFor();
  for (const iso of ["ARE","OMN","BHR","KWT","QAT","IRQ","IRN","EGY"]) assert.equal(await box("country:"+iso).count(),1);
  await search.fill("مِصْر");
  await box("country:EGY").check();
  const egypt=await count();
  await search.fill("KSA");
  await box("country:SAU").check();
  const union=await count();
  await button("Remove Egypt").click();
  const saudi=await count();
  assert.equal(union, egypt+saudi, "points in disjoint countries are counted once");
  assert.ok(saudi>0 && union<initial);
  await button("Clear all").click();
  await button("GCC countries").click();
  assert.equal(await page.locator(".place-selections button[aria-label]").count(),6);
  await button("Whole Arabian Gulf").click();
  assert.equal(await page.locator(".place-selections button[aria-label]").count(),9);
  await search.fill("Persian Gulf");
  assert.equal(await box("sea:gulf").isChecked(),true);
  await button("Clear all").click();
  await button("Cities").click();
  const countryScope = page.getByRole("combobox",{name:"Search within country"});
  await countryScope.selectOption("QAT");
  await search.fill("الدوحة");
  assert.ok(await page.locator(".place-results label").filter({hasText:"Qatar"}).count()>0);
  await countryScope.selectOption("BHR");
  await search.fill("المنامة");
  assert.ok(await page.locator(".place-results label").filter({hasText:"Bahrain"}).count()>0);
  await button("Waters").click();
  await search.fill("الخليج");
  await box("sea:gulf").check();
  await page.locator(".leaflet-places-pane path[d]").first().waitFor({state:"attached"});
  await button("Show on map").click();
  await button("Filter places").click();
  await button("Clear all").click();
  await page.getByRole("button",{name:"English / العربية"}).click();
  await search.fill("الرياض");
  const riyadh = page.locator('.place-results label').filter({has:page.getByText("الرياض",{exact:true})});
  assert.ok(await riyadh.filter({hasText:"منطقة إدارية"}).count()>0);
  await riyadh.filter({hasText:"٢٥ كم"}).first().getByRole("checkbox").check();
  await search.fill("xqz-not-a-place");
  assert.equal(await page.locator(".place-results input").count(),0);
  assert.equal(await page.locator(".place-selections button[aria-label]").count(),1);
  await button("عرض على الخريطة").click();
  await button("فلترة الأماكن").click();
  await button("مسح الكل").click();
  await page.getByRole("button",{name:"English / العربية"}).click();
  await button("Close panel").click();
  assert.equal(await count(),initial);
  await button("Fit region").click();
}
